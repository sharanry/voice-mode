#!/bin/sh
# Generates Generated/Secrets.swift from .env so API keys never live in tracked source.
# Runs as an Xcode pre-build phase; safe to run by hand.
set -eu
ROOT="${SRCROOT:-$(cd "$(dirname "$0")/.." && pwd)}"
ENV_FILE="$ROOT/.env"
OUT="$ROOT/Generated/Secrets.swift"

# Prints the value of the first key (in argument order) that is set in .env.
value() {
  [ -f "$ENV_FILE" ] || return 0
  for key in "$@"; do
    v=$(grep -E "^[[:space:]]*(export[[:space:]]+)?$key[[:space:]]*=" "$ENV_FILE" | tail -n 1 \
      | sed -E "s/^[^=]*=[[:space:]]*//; s/[[:space:]]+\$//; s/^\"(.*)\"\$/\\1/; s/^'(.*)'\$/\\1/")
    if [ -n "$v" ]; then printf '%s' "$v"; return 0; fi
  done
}

API_KEY=$(value ELEVENLABS_API_KEY ELEVEN_LABS_API_KEY ELEVEN_API_KEY XI_API_KEY)
VOICE_ID=$(value ELEVENLABS_VOICE_ID)
MODEL_ID=$(value ELEVENLABS_MODEL_ID)
OPENROUTER_KEY=$(value OPENROUTER_API_KEY)
OPENROUTER_MODEL=$(value OPENROUTER_MODEL)

mkdir -p "$(dirname "$OUT")"
TMP=$(mktemp)
cat > "$TMP" <<SWIFT
// Generated by scripts/generate-secrets.sh from .env. Do not edit or commit.
nonisolated enum Secrets {
    static let elevenLabsAPIKey = "$API_KEY"
    static let elevenLabsVoiceID = "$VOICE_ID"
    static let elevenLabsModelID = "$MODEL_ID"
    static let openRouterAPIKey = "$OPENROUTER_KEY"
    static let openRouterModel = "$OPENROUTER_MODEL"
}
SWIFT
# Only touch the file when it changes so Xcode doesn't recompile every build.
if cmp -s "$TMP" "$OUT" 2>/dev/null; then rm "$TMP"; else mv "$TMP" "$OUT"; fi
